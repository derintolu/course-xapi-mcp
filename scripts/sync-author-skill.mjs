// Regenerates reference/packages/validator/src/author-skill.generated.ts from docs/authoring/SKILL.md,
// so the validator's MCP server serves the author skill without file access.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../docs/authoring/SKILL.md', import.meta.url);
if (!existsSync(source)) {
  console.error('sync-author-skill: docs/authoring/SKILL.md not found; it is the source of author-skill.generated.ts. Nothing written.');
  process.exit(1);
}
const md = readFileSync(source, 'utf8');
const out = `// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/sync-author-skill.mjs from docs/authoring/SKILL.md. Do not edit by hand.\nexport const AUTHOR_SKILL = ${JSON.stringify(md)};\n`;
writeFileSync(new URL('../reference/packages/validator/src/author-skill.generated.ts', import.meta.url), out);
console.log('wrote author-skill.generated.ts');
