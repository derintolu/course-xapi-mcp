// Regenerates reference/packages/core/src/agent-rules.generated.ts from rules/AGENT_RULES.md,
// so the rules text ships inside the core library (no file access needed in workers).
import { readFileSync, writeFileSync } from 'node:fs';

const md = readFileSync(new URL('../rules/AGENT_RULES.md', import.meta.url), 'utf8');
const out = `// Generated by scripts/sync-rules.mjs from rules/AGENT_RULES.md. Do not edit by hand.\nexport const AGENT_RULES = ${JSON.stringify(md)};\n`;
writeFileSync(new URL('../reference/packages/core/src/agent-rules.generated.ts', import.meta.url), out);
console.log('wrote agent-rules.generated.ts');
